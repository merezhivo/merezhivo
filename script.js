const languageButtons = document.querySelectorAll(".lang-button");

function setLanguage(language) {
  const dictionary = translations[language];
  if (!dictionary) return;

  document.documentElement.lang = language;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) {
      element.innerHTML = dictionary[key];
    }
  });

  languageButtons.forEach((button) => {
    const isActive = button.dataset.lang === language;
    button.classList.toggle("active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  try {
    localStorage.setItem("merezhivo-language", language);
  } catch (error) {
    // Language switching still works if browser storage is unavailable.
  }
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => {
    setLanguage(button.dataset.lang);
  });
});

// Mobile navigation
const menuToggle = document.querySelector(".menu-toggle");
const mobileNav = document.querySelector(".mobile-nav");

menuToggle.addEventListener("click", () => {
  const isOpen = mobileNav.classList.toggle("open");
  menuToggle.setAttribute("aria-expanded", String(isOpen));
});

mobileNav.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => {
    mobileNav.classList.remove("open");
    menuToggle.setAttribute("aria-expanded", "false");
  });
});

// Restore selected language
try {
  const savedLanguage = localStorage.getItem("merezhivo-language");
  if (savedLanguage && translations[savedLanguage]) {
    setLanguage(savedLanguage);
  }
} catch (error) {
  setLanguage("uk");
}

// Rotate the lace ring of every logo with the page scroll (eased).
// The centre layer (tree + lettering) is never rotated, so the text stays readable.
(() => {
  const rings = document.querySelectorAll(".logo-ring");
  if (!rings.length) return;
  if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;

  const DEG_PER_PX = 0.06; // 1000px of scrolling = 60deg
  let current = 0;
  let running = false;

  const frame = () => {
    const target = window.scrollY * DEG_PER_PX;
    current += (target - current) * 0.12;
    rings.forEach((ring) => {
      ring.style.transform = `rotate(${current.toFixed(2)}deg)`;
    });
    if (Math.abs(target - current) > 0.02) {
      requestAnimationFrame(frame);
    } else {
      running = false;
    }
  };

  const start = () => {
    if (!running) {
      running = true;
      requestAnimationFrame(frame);
    }
  };

  window.addEventListener("scroll", start, { passive: true });
  start();
})();
